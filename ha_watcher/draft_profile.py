"""Generate a DRAFT profile for one device from captured data (Phase 4: "Grokbot generates the initial
profile from the captured payload; you eyeball entity ID mappings before it goes live").

    python -m ha_watcher.draft_profile --device-id <id> [--from-log FILE | --from-snapshot FILE | --live]
                                       [--profiles-dir profiles] [--out FILE]

Writes `status: draft` YAML in the current schema (docs/profile-schema.md) to <profiles-dir>/<name>.yaml.
Never overwrites an existing file. Values come from the real payload; entity-ID cleanup, dashboard card and
entity_patterns suggestions are COMMENTED hints for you to review. The result passes
`python -m ha_watcher.provision --check-profiles`. Drafts are never matched until set to `status: active`.
"""
from __future__ import annotations

import argparse
import asyncio
import datetime as dt
import json
import logging
import os
import sys

import yaml

from . import snapshot
from .client import AuthFailed, HAClient
from .profiles import load_profiles
from .report import build_stub, summarize

EXIT_OK, EXIT_ERROR, EXIT_AUTH_FAILED, EXIT_CONFIG_ERROR, EXIT_EXISTS = 0, 1, 2, 3, 4
CARD_DOMAIN_ORDER = ("light", "switch", "media_player", "climate", "cover", "fan", "lock", "sensor",
                     "binary_sensor", "select", "number", "update")


def _y(value) -> str:
    """One-line, always-valid YAML (JSON is a subset of YAML), so uncommented hints keep their quoting."""
    return json.dumps(value, ensure_ascii=False)


def entity_hints(entity_ids: list[str] | None, device_name: str | None):
    """(pattern suggestions, cleanup rule suggestions, card suggestion) from a device's entity IDs."""
    from .placeholders import slugify
    if not entity_ids:
        return [], [], None
    ids = sorted(entity_ids)
    by_domain: dict[str, list[str]] = {}
    for e in ids:
        by_domain.setdefault(e.split(".", 1)[0], []).append(e)
    patterns = [f"{d}.*" for d in sorted(by_domain)]  # '<domain>.*' survives renames
    prefix = slugify(device_name or "")
    rules = []
    for e in ids:
        dom, obj = e.split(".", 1)
        suffix = ""
        if len(by_domain[dom]) > 1:
            suffix = obj[len(prefix):].strip("_") if prefix and obj.startswith(prefix) else obj
        to = f"{dom}.{{area}}_{{name}}" + (f"_{suffix}" if suffix else "")
        rules.append({"from": e, "to": to})
    doms = [d for d in CARD_DOMAIN_ORDER if d in by_domain] or sorted(by_domain)
    card = {"type": "entities", "title": "{device_name}", "entities": [f"{{entity:{d}}}" for d in doms[:3]]}
    return patterns, rules, card


def render(d: dict, source_desc: str) -> str:
    stub = build_stub(d)
    patterns, rules, card = entity_hints(d.get("entity_ids"), d.get("name"))
    m = stub["match"]
    ts = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    out = [
        f"# DRAFT profile generated by ha_watcher.draft_profile on {ts} from {source_desc}.",
        f"# Device: {d.get('name') or '?'} ({d['device_id']}). Values below are from the captured payload.",
        "# Review everything, then set `status: active`. Schema and placeholders: docs/profile-schema.md",
        "# Validate: python -m ha_watcher.provision --check-profiles --profiles-dir profiles",
        "# Replay on this device (dry-run): python -m ha_watcher.provision --device-id " + d["device_id"],
        f"name: {stub['name']}",
        f"description: {_y('Draft for ' + ' '.join(x for x in (d.get('manufacturer'), d.get('model')) if x) or 'unknown device')}",
        "status: draft",
        "",
        "match:",
        f"  manufacturer: {_y(m['manufacturer'])}",
        f"  model: {_y(m['model'])}",
    ]
    if patterns:
        out += ["  # Optional entity_patterns: every pattern must match one of the device's CURRENT entity IDs.",
                "  # Matching uses current ids, so prefer patterns that still fit after entity_id_cleanup renames.",
                "  # entity_patterns:"] + [f"  #   - {_y(p)}" for p in patterns]
    else:
        out += ["  # entity_patterns: [\"light.*\"]   # optional; entity IDs were not in this source (use --live or a snapshot)"]
    out += [
        "",
        "recipe:",
        "  name: null          # device name to set, e.g. \"Living Room {model}\"; null = leave as is",
        "  area: null          # an EXISTING area name (e.g. \"Living Room\"); null = skip (area_unresolved)",
        "  entity_id_cleanup: []",
    ]
    if rules:
        out += ["  # Hints (delete the `[]` line above, uncomment, adjust). 'from' is a glob over entity IDs; {area} and {name} are slugs.",
                "  # Check every mapping: renaming does not update dashboards/automations that use the old id.",
                "  # entity_id_cleanup:"]
        for r in rules:
            out += [f"  #   - from: {_y(r['from'])}", f"  #     to: {_y(r['to'])}"]
    else:
        out += ["  # entity_id_cleanup:",
                "  #   - from: \"light.some_entity*\"",
                "  #     to: \"light.{area}_{name}\""]
    out += ["  dashboard_card: null"]
    if card:
        out += ["  # dashboard_card:           # delete the `null` line above; storage-mode dashboards only; {entity:<domain>} = first such entity",
                "  #   dashboard: lovelace",
                "  #   view: <view path or title>",
                f"  #   card: {_y(card)}"]
    else:
        out += ["  # dashboard_card:", "  #   dashboard: lovelace", "  #   view: <view path or title>",
                "  #   card: {type: entities, title: \"{device_name}\", entities: [\"{entity:light}\"]}"]
    out += ["  welcome_automation: null   # e.g. automation.welcome_my_device (must exist)", "", "source:"]
    out += ["  " + line for line in yaml.safe_dump(stub["source"], sort_keys=False).rstrip().splitlines()]
    return "\n".join(out) + "\n"


def parse_args(argv=None) -> argparse.Namespace:
    p = argparse.ArgumentParser(prog="ha_watcher.draft_profile", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--device-id", required=True)
    src = p.add_mutually_exclusive_group()
    src.add_argument("--from-log", metavar="FILE", help="capture log (rotated backups are read too)")
    src.add_argument("--from-snapshot", metavar="FILE", help="snapshot written by ha_watcher.snapshot")
    src.add_argument("--live", action="store_true", help="read the device from Home Assistant now (default)")
    p.add_argument("--profiles-dir", default=os.environ.get("HA_WATCHER_PROFILES", "profiles"))
    p.add_argument("--out", help="write here instead of <profiles-dir>/<name>.yaml (still never overwrites)")
    p.add_argument("--url", default=os.environ.get("HA_URL"))
    p.add_argument("--timeout", type=float, default=30.0)
    return p.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    logging.basicConfig(level=logging.WARNING, stream=sys.stderr)
    existing = load_profiles(args.profiles_dir)
    live_records: list[dict] = []
    if args.from_log or args.from_snapshot:
        path = args.from_log or args.from_snapshot
        if not os.path.exists(path):
            print(f"ERROR: {path} not found", file=sys.stderr)
            return EXIT_CONFIG_ERROR
        rep = summarize(path if args.from_log else "/nonexistent/none.jsonl", args.profiles_dir,
                        [path] if args.from_snapshot else [])
        source_desc = f"{'capture log' if args.from_log else 'snapshot'} {os.path.basename(path)}"
    else:
        token = os.environ.get("HA_TOKEN")
        if not args.url or not token:
            print("ERROR: --live needs HA_URL (or --url) and HA_TOKEN", file=sys.stderr)
            return EXIT_CONFIG_ERROR

        async def fetch() -> list[dict]:
            async with HAClient(args.url, token, args.timeout) as ha:
                return await snapshot.take_snapshot(ha.call, existing.profiles)
        try:
            live_records = asyncio.run(fetch())
        except AuthFailed as exc:
            print(f"FATAL: Home Assistant rejected the token (auth_invalid): {exc}", file=sys.stderr)
            return EXIT_AUTH_FAILED
        except (OSError, ConnectionError, RuntimeError, asyncio.TimeoutError) as exc:
            print(f"ERROR: could not read from Home Assistant: {exc!r}", file=sys.stderr)
            return EXIT_ERROR
        rep = summarize("/nonexistent/none.jsonl", args.profiles_dir, (), extra_records=live_records)
        source_desc = "live Home Assistant registry"

    dev = next((d for d in rep["devices"] if d["device_id"] == args.device_id), None)
    if dev is None:
        print(f"ERROR: device {args.device_id} not found in {source_desc}", file=sys.stderr)
        return EXIT_ERROR
    if dev["matched"]:
        print(f"NOTE: this device already matches active profile {dev['profile_name']!r} "
              f"({dev['profile_match']}); generating a draft anyway.", file=sys.stderr)

    text = render(dev, source_desc)
    path = args.out or os.path.join(args.profiles_dir, build_stub(dev)["name"] + ".yaml")
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    try:
        with open(path, "x", encoding="utf-8") as fh:  # 'x': never overwrite
            fh.write(text)
    except FileExistsError:
        print(f"ERROR: {path} already exists; not overwriting (use --out to write elsewhere)", file=sys.stderr)
        return EXIT_EXISTS
    print(path)
    print("draft written (status: draft, never matched). Next: edit it, set status: active, then "
          f"`python -m ha_watcher.provision --device-id {args.device_id}` to replay (dry-run).", file=sys.stderr)
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
